// Run against the isolated web-ui-host fixture using playwright-cli run-code.
async (page) => {
  await page.getByRole('button', { name: 'A new home for Shepherd', exact: true }).click();
  await page.getByText('Connected', { exact: true }).waitFor();
  const composer = page.getByRole('textbox', { name: 'Message Shepherd' });
  await composer.fill('Keep this turn');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText('Keep this turn', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Stop response', exact: true }).waitFor({ state: 'hidden' });
  await composer.fill('Remove this turn');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByRole('button', { name: 'Stop response', exact: true }).waitFor({ state: 'hidden' });
  await page.getByText('Remove this turn', { exact: true }).waitFor();
  const open = () => page.getByRole('button', { name: 'Conversation actions', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Conversation actions', exact: true });
  await open();
  await dialog.getByLabel('Recent turns to remove', { exact: true }).fill('0');
  if (await dialog.getByRole('button', { name: 'Roll back conversation', exact: true }).isEnabled()) throw Error('Invalid count accepted');
  await dialog.getByLabel('Recent turns to remove', { exact: true }).fill('1');
  await dialog.getByRole('button', { name: 'Roll back conversation', exact: true }).click();
  await dialog.getByText('It does not undo file edits', { exact: false }).waitFor();
  await dialog.getByRole('button', { name: 'Cancel rollback', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByText('Remove this turn', { exact: true }).waitFor();

  // Hold a pre-rollback history snapshot across the mutation to exercise stale-response recovery.
  let release;
  let captured;
  const waiting = new Promise(resolve => { captured = resolve; });
  let first = true;
  await page.route('**/api/v1/conversations/*/turns?*', async route => {
    if (!first) return route.continue();
    first = false;
    const response = await route.fetch();
    await new Promise(resolve => { release = resolve; captured(); });
    await route.fulfill({ response }).catch(() => {});
  });
  await page.evaluate(() => window.dispatchEvent(new Event('offline')));
  await waiting;
  await page.getByText('Connected', { exact: true }).waitFor();
  await open();
  await dialog.getByRole('button', { name: 'Roll back conversation', exact: true }).click();
  const response = page.waitForResponse(response => response.url().endsWith('/rollback'));
  await dialog.getByRole('button', { name: 'Confirm rollback', exact: true }).click();
  await response; release();
  await dialog.getByText('Rolled back 1 turn. Files were not changed.', { exact: true }).waitFor();
  await page.unroute('**/api/v1/conversations/*/turns?*');
  await page.keyboard.press('Escape');
  await page.getByText('Keep this turn', { exact: true }).waitFor();
  if (await page.getByText('Remove this turn', { exact: true }).count()) throw Error('Rolled-back history survived refresh');
  await page.reload();
  await page.getByText('Connected', { exact: true }).waitFor();
  await page.getByText('Keep this turn', { exact: true }).waitFor();
  if (await page.getByText('Remove this turn', { exact: true }).count()) throw Error('Old SSE replay restored removed turn');
  await open();
  await dialog.getByRole('button', { name: 'Compact conversation', exact: true }).click();
  await dialog.getByText('Compaction started.', { exact: false }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByText('Compacting context', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Stop response', exact: true }).waitFor({ state: 'hidden' });
  await open();
  await page.route('**/api/v1/conversations/*/rollback', route => route.fulfill({ status: 502, json: { error: { code: 'operation_failed', message: 'Rollback unavailable' } } }));
  await dialog.getByRole('button', { name: 'Roll back conversation', exact: true }).click();
  await dialog.getByRole('button', { name: 'Confirm rollback', exact: true }).click();
  await dialog.getByText('Rollback unavailable', { exact: false }).waitFor();
  if (await dialog.getByRole('button', { name: 'Confirm rollback', exact: true }).isEnabled()) throw Error('Uncertain mutation allows immediate retry');
  await dialog.getByRole('button', { name: 'Reload conversation to check outcome', exact: true }).click();
  await page.unroute('**/api/v1/conversations/*/rollback');
  await open();
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.getByLabel('Recent turns to remove', { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/shepherd-history-actions-mobile.png' });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('History actions overflow');
  await page.keyboard.press('Escape');
  await composer.fill('approval');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByRole('button', { name: 'Allow once', exact: true }).waitFor();
  await open();
  for (const name of ['Compact conversation', 'Roll back conversation']) if (await dialog.getByRole('button', { name, exact: true }).isEnabled()) throw Error('Active history action enabled');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Allow once', exact: true }).click();
}
