// Run against the isolated web-ui-host fixture with playwright-cli run-code.
async (page) => {
  await page.getByRole('button', { name: 'A new home for Shepherd', exact: true }).click();
  await page.getByRole('button', { name: 'Resume conversation', exact: true }).click();
  await page.getByText('Connected', { exact: true }).waitFor();
  const actions = page.getByRole('dialog', { name: 'Conversation actions', exact: true });
  await page.getByRole('button', { name: 'Conversation actions', exact: true }).click();
  await actions.getByLabel('Conversation name', { exact: true }).fill('Renamed source');
  await actions.getByRole('button', { name: 'Save name', exact: true }).click();
  await page.getByRole('heading', { name: 'Renamed source', exact: true }).waitFor();
  const source = await page.evaluate(() => JSON.parse(localStorage.getItem('shepherd.selection')));
  await page.getByRole('button', { name: 'Conversation actions', exact: true }).click();
  await actions.getByRole('button', { name: 'Fork conversation', exact: true }).click();
  await page.getByRole('heading', { name: 'Fork copy', exact: true }).waitFor();
  const fork = await page.evaluate(() => JSON.parse(localStorage.getItem('shepherd.selection')));
  if (source.id === fork.id || source.threadId === fork.threadId) throw Error('Fork reused source');
  await page.getByRole('button', { name: 'Renamed source', exact: true }).waitFor();
  await page.getByText('Where did we leave off?', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Conversation actions', exact: true }).click();
  await actions.getByRole('button', { name: 'Archive conversation', exact: true }).click();
  await actions.getByRole('button', { name: 'Confirm archive', exact: true }).click();
  await page.getByRole('heading', { name: 'Workspace', exact: true }).waitFor();
  if (await page.evaluate(() => localStorage.getItem('shepherd.selection'))) throw Error('Archived selection persisted');
  await page.getByRole('button', { name: 'Archived', exact: true }).click();
  await page.getByRole('button', { name: 'Restore Fork copy', exact: true }).click();
  await page.getByRole('button', { name: 'Fork copy', exact: true }).click();
  await page.getByRole('button', { name: 'Resume conversation', exact: true }).click();
  await page.getByText('Connected', { exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Fork copy', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Message Shepherd' }).fill('approval');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByRole('button', { name: 'Allow once', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Conversation actions', exact: true }).click();
  if (!await actions.getByRole('button', { name: 'Fork conversation', exact: true }).isDisabled()) throw Error('Active fork enabled');
  if (!await actions.getByRole('button', { name: 'Archive conversation', exact: true }).isDisabled()) throw Error('Active archive enabled');
  await actions.getByRole('button', { name: 'Close conversation actions', exact: true }).click();
  await page.getByRole('button', { name: 'Allow once', exact: true }).click();
  await page.getByText('Connected', { exact: true }).waitFor();
  let release;
  await page.route('**/api/v1/threads?*archived=true', async route => { await new Promise(resolve => { release = resolve; }); await route.fulfill({ json: { threads: [], nextCursor: null, backwardsCursor: null } }); });
  await page.getByRole('button', { name: 'Archived', exact: true }).click();
  await page.waitForTimeout(100);
  await page.getByRole('button', { name: 'Active', exact: true }).click();
  await page.getByRole('button', { name: 'Renamed source', exact: true }).waitFor();
  release(); await page.waitForTimeout(100);
  if (!await page.getByRole('button', { name: 'Renamed source', exact: true }).isVisible()) throw Error('Stale archived response replaced active list');
  await page.unroute('**/api/v1/threads?*archived=true');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Conversation actions', exact: true }).click();
  await actions.waitFor();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Narrow layout overflow');
  await page.screenshot({ path: '/tmp/shepherd-management-mobile.png' });
  await page.keyboard.press('Escape');
  if (await actions.isVisible()) throw Error('Escape failed');
}
