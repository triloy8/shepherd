// Run against the isolated web-ui-host fixture using playwright-cli run-code.
async (page) => {
  await page.getByRole('button', { name: 'A new home for Shepherd', exact: true }).click();
  await page.getByText('Connected', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Model and effort', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Model and effort', exact: true });
  await dialog.getByRole('button', { name: 'More models', exact: true }).click();
  await dialog.getByLabel('Model for next turn', { exact: true }).selectOption('large');
  await dialog.getByRole('button', { name: 'Use model', exact: true }).click();
  await dialog.getByLabel('Effort for next turn', { exact: true }).locator('option[value="high"]').waitFor({ state: 'attached' });
  await dialog.getByLabel('Effort for next turn', { exact: true }).selectOption('high');
  await dialog.getByRole('button', { name: 'Use effort', exact: true }).click();
  await dialog.getByText('Current and pending values', { exact: true }).click();
  await dialog.locator('dd').filter({ hasText: /^high$/ }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/shepherd-settings-mobile.png' });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Settings overflow');
  await dialog.getByRole('button', { name: 'Close settings', exact: true }).click();
  const controls = page.getByRole('button', { name: 'Model and effort', exact: true });
  await controls.getByText('large · high', { exact: true }).waitFor();
  if (!await controls.evaluate(el => el === document.activeElement)) throw Error('Picker did not restore composer control focus');
  await page.getByRole('button', { name: 'Conversation context', exact: true }).click();
  const context = page.getByRole('dialog', { name: 'Conversation context', exact: true });
  await context.getByText('No context telemetry yet. Send a turn first.', { exact: true }).waitFor();
  if (await context.getByText('Banked resets', { exact: false }).count()) throw Error('Account usage leaked into context');
  await context.getByRole('button', { name: 'Compact conversation', exact: true }).click();
  await page.getByRole('dialog', { name: 'Compact conversation', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  if (!await page.getByRole('button', { name: 'Conversation context', exact: true }).evaluate(el => el === document.activeElement)) throw Error('Compaction dialog did not restore context control focus');
  await page.reload();
  await page.getByRole('button', { name: 'Model and effort', exact: true }).click();
  await dialog.getByText('Current and pending values', { exact: true }).click();
  await dialog.locator('dd').filter({ hasText: /^large$/ }).waitFor();
  await dialog.locator('dd').filter({ hasText: /^high$/ }).waitFor();
  await dialog.getByLabel('Effort for next turn', { exact: true }).selectOption('default');
  await dialog.getByRole('button', { name: 'Use effort', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('select[aria-label="Effort for next turn"]')?.value === 'low');
  await page.keyboard.press('Escape');
  if (await dialog.isVisible()) throw Error('Escape did not close settings');
}
